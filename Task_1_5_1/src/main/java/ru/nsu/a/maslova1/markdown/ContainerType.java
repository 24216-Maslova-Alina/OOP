package ru.nsu.a.maslova1.markdown;

/**
 * Перечисление, представляющее типы контейнеров для группировки элементов.
 */
public enum ContainerType {
    /**
     * Неупорядоченный список (маркированный список).
     */
    UNORDERED_LIST,

    /**
     * Упорядоченный список (нумерованный список).
     */
    ORDERED_LIST
}